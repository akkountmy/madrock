/**
 * Обновление README после правок: шапка, слот логотипа, список инструментов.
 * Запуск: node tools/readme-update.mjs
 */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const file = 'README.md'

const EDITS = [
  ['1. **Шапка** — липкая навигация, статус «Открыто до 23:00» по реальному времени, счётчики кабинета и предзаказа.',
   '1. **Шапка** — пять пунктов меню (Меню, Предзаказ, Бонусы, О нас, Контакты), статус «Открыто до 23:00» по реальному времени, личный кабинет и предзаказ открываются иконками справа. Активный пункт подсвечивается золотом и меняет цвет при нажатии.'],

  ['    fetch-photos.mjs  ← загрузка фото (Unsplash CDN)\n    fetch-photos-2.mjs← добор фото (Wikimedia Commons)',
   '    fetch-photos.mjs  ← загрузка фото (Unsplash CDN)\n    fetch-photos-2.mjs← добор фото (Wikimedia Commons)\n    fetch-brand*.mjs  ← попытки забрать бренд из Instagram/VK/каталогов\n    brand-colors.ps1  ← разбор палитры реальных фото кофейни\n    fix-copy.mjs      ← правки текстов («точки» → «кофейни»), чистка шапки\n    fix-copy-2.mjs    ← подсветка меню и адаптив карточки напитка\n    fix-logo.mjs      ← слот настоящего логотипа в шапке\n    fix-audit.mjs     ← бейджи «Хит» и защита от горизонтальной прокрутки\n    fix-hidden.mjs    ← скрытые панели вне потока (visibility)'],
]

let text = await readFile(join(root, file), 'utf8')
const problems = []
let applied = 0
for (const [from, to] of EDITS) {
  const parts = text.split(from)
  if (parts.length - 1 !== 1) { problems.push(`не найдено ровно один раз: «${from.slice(0, 60)}…»`); continue }
  text = parts.join(to)
  applied += 1
}

const LOGO_SECTION = `

## Логотип

В шапке стоит нарисованный знак MADROCK, но рядом уже есть слот под настоящий логотип:
достаточно положить файл **\`assets/brand/logo.png\`** — он появится в шапке сам, без правок кода
(если файла нет, картинка убирает себя и остаётся нарисованный знак). Тот же файл используется
как иконка для добавления сайта на телефон.

Почему логотип не подставлен сразу: Instagram отдаёт анонимным запросам страницу ошибки,
VK требует токен, зеркала закрыты (403). Из открытых источников удалось получить только
реальные фотографии заведения — по ним и собрана палитра (см. ниже).

## Палитра и бренд

Разбор насыщенных цветов реальных фотографий кофейни (\`tools/brand-colors.ps1\`) даёт
устойчивое сочетание: глубокая синева (${'`'}#3B617A${'`'}, ${'`'}#267284${'`'}, ${'`'}#446FA2${'`'}) и тёплое дерево
(${'`'}#8A6D4B${'`'}, ${'`'}#A2825A${'`'}). Сайт пока построен на тёплой янтарной базе; если синева — это
действительно бренд, палитра меняется в одном месте — блоке токенов в \`src/styles.css\`.

## Аудит вёрстки

Браузерный аудит (\`Аудит MADROCK\` в интерфейсе) прожимает все пункты меню, категории, фильтры,
корзину, карточку напитка, оформление заказа и избранное и измеряет на шести ширинах
(390–1440 px): горизонтальную прокрутку, обрезку текста и симметрию полей. Последний прогон —
27 проверок, 0 замечаний.
`

if (text.indexOf('## Логотип') < 0) {
  text = text.trimEnd() + '\n' + LOGO_SECTION
  applied += 1
}

if (problems.length) {
  console.log('ПРАВКИ НЕ ПРИМЕНЕНЫ:')
  problems.forEach((p) => console.log('  ✗ ' + p))
  process.exitCode = 1
} else {
  await writeFile(join(root, file), text, 'utf8')
  console.log(`обновлён ${file}, правок: ${applied}`)
}
